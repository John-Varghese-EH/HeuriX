#!/usr/bin/env python3
"""
Cross-Platform Threat Simulation Engine
========================================
Simulates real-world benign and double-extortion ransomware workloads for IEEE paper benchmarks.

Modes:
  1. Benign Workload: Rapid AI code generation (Node.js/C++/Python files), build tool compilation.
  2. Malicious Encryption: Directory-targeting encryption patterns mimicking 2026 double-extortion
     strains (Qilin, Akira, Play, INC Ransom).
  3. C2 Network Exfiltration: Simulates TLS/HTTPS exfiltration traffic to model double-extortion channels.
"""

import argparse
import math
import os
import random
import socket
import string
import sys
import time
from pathlib import Path
from typing import List


def generate_high_entropy_payload(size: int = 4096) -> bytes:
    """Generates cryptographically random pseudo-bytes with entropy > 7.9."""
    return bytes(random.getrandbits(8) for _ in range(size))


def generate_code_payload(language: str = "cpp") -> str:
    """Generates synthetic code content simulating an AI code assistant."""
    if language == "cpp":
        return f"""// Auto-generated by AI Assistant {random.randint(1000, 9999)}
#include <iostream>
#include <vector>

void process_data_{random.randint(1, 100)}() {{
    std::vector<int> vec = {{{random.randint(1, 100)}, {random.randint(101, 200)}}};
    std::cout << "Processing vector size: " << vec.size() << std::endl;
}}
"""
    else:
        return f"""// Auto-generated Node.js module {random.randint(1000, 9999)}
const fs = require('fs');
const path = require('path');

function executeTask{random.randint(1, 100)}() {{
    console.log("Executing task at timestamp:", Date.now());
}}

module.exports = {{ executeTask{random.randint(1, 100)} }};
"""


class ThreatSimulator:
    """Simulator for benign activity, ransomware encryption, and C2 exfiltration."""

    def __init__(self, target_dir: str):
        self.target_dir = Path(target_dir).resolve()
        self.target_dir.mkdir(parents=True, exist_ok=True)

    def run_benign_ai_editor(self, duration_sec: int = 10, files_per_sec: int = 5):
        """Simulates rapid benign file generation from an AI code editor (e.g. Cursor, Copilot)."""
        print(f"[*] [Benign] Simulating AI Code Editor activity for {duration_sec}s...")
        end_time = time.time() + duration_sec
        count = 0

        while time.time() < end_time:
            lang = random.choice(["cpp", "js"])
            ext = ".cpp" if lang == "cpp" else ".js"
            filepath = self.target_dir / f"generated_module_{count}{ext}"
            
            with open(filepath, "w") as f:
                f.write(generate_code_payload(lang))
            
            count += 1
            time.sleep(1.0 / files_per_sec)

        print(f"[+] [Benign] Created {count} benign code files without security alerts.")

    def run_qilin_akira_simulation(self, target_extensions: List[str] = None):
        """
        Simulates Qilin/Akira ransomware behavior:
        - Target specific high-value file formats (.pdf, .docx, .xlsx, .db)
        - Fast directory traversal & in-place high-entropy encryption
        - Appending ransom extensions (.qilin, .akira)
        """
        if not target_extensions:
            target_extensions = [".pdf", ".docx", ".xlsx", ".db", ".cpp", ".txt"]

        print(f"[!] [Attack] Simulating Qilin/Akira-style ransomware in {self.target_dir}...")
        
        # 1. Populate victim directory if empty
        victim_files = list(self.target_dir.rglob("*"))
        victim_files = [f for f in victim_files if f.is_file() and not f.name.endswith(".locked")]
        
        if len(victim_files) < 10:
            print("[*] Seeding victim directory with sample documents...")
            for i in range(20):
                ext = random.choice(target_extensions)
                vf = self.target_dir / f"financial_doc_{i}{ext}"
                with open(vf, "wb") as f:
                    f.write(b"%PDF-1.4 Header\nSample sensitive data\n" * 20)
                victim_files.append(vf)

        start_time = time.time()
        encrypted_count = 0

        # 2. Perform rapid high-entropy overwrite + rename
        for vf in victim_files:
            try:
                # Overwrite first 4KB with pseudo-random high entropy payload
                payload = generate_high_entropy_payload(4096)
                with open(vf, "r+b") as f:
                    f.write(payload)

                # Rename with ransomware extension
                ransom_ext = random.choice([".qilin", ".akira", ".locked"])
                new_path = vf.with_suffix(vf.suffix + ransom_ext)
                vf.rename(new_path)
                encrypted_count += 1
            except Exception as e:
                continue

            time.sleep(0.01)  # High velocity burst

        elapsed = time.time() - start_time
        print(f"[!] [Attack] Encrypted {encrypted_count} files in {elapsed:.3f} seconds.")

    def run_c2_exfiltration_simulation(self, host: str = "127.0.0.1", port: int = 443, data_mb: int = 1):
        """Simulates C2 exfiltration network traffic for double-extortion modeling."""
        print(f"[!] [C2] Simulating {data_mb}MB network exfiltration channel...")
        dummy_data = b"X" * 1024
        sent_bytes = 0
        total_target = data_mb * 1024 * 1024

        try:
            # We open a socket attempt to simulate flow
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(0.5)
            try:
                sock.connect((host, port))
                while sent_bytes < total_target:
                    sock.sendall(dummy_data)
                    sent_bytes += len(dummy_data)
            except Exception:
                # Simulated fallback transfer loop
                while sent_bytes < total_target:
                    sent_bytes += 1024
                    time.sleep(0.0001)
            finally:
                sock.close()
        except Exception:
            pass

        print(f"[+] [C2] Simulated {sent_bytes / (1024*1024):.1f}MB exfiltration payload.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Cross-Platform Threat Simulator")
    parser.add_argument("--mode", choices=["benign", "attack", "c2"], required=True)
    parser.add_argument("--target-dir", default="./test_sandbox")
    args = parser.parse_args()

    sim = ThreatSimulator(args.target_dir)
    if args.mode == "benign":
        sim.run_benign_ai_editor()
    elif args.mode == "attack":
        sim.run_qilin_akira_simulation()
    elif args.mode == "c2":
        sim.run_c2_exfiltration_simulation()
